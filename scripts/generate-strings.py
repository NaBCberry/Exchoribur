#!/usr/bin/env python3
"""从 Strings.resx 生成强类型 C# 访问器;--check 只验证,不写入文件。"""

import argparse
from pathlib import Path
import re
import sys
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parent.parent
RESX = ROOT / "src/Exchoribur.App/Resources/Strings.resx"
OUTPUT = ROOT / "src/Exchoribur.App/Resources/Strings.g.cs"


def render() -> str:
    keys = [node.attrib["name"] for node in ET.parse(RESX).getroot().findall("data")]
    if not keys or len(keys) != len(set(keys)):
        raise ValueError("资源键不能为空或重复")
    if any(not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", key) for key in keys):
        raise ValueError("资源键必须是有效的 C# 标识符")
    lines = [
        "// <auto-generated />",
        "// 由 scripts/generate-strings.py 从 Strings.resx 生成,不要手改。",
        "",
        "using System.Resources;",
        "",
        "namespace Exchoribur.App.Resources;",
        "",
        "/// <summary>界面文案,正文位于 Strings.resx。</summary>",
        "internal static class Strings",
        "{",
        '    private static readonly ResourceManager Manager = new("Exchoribur.App.Resources.Strings", typeof(Strings).Assembly);',
        "",
    ]
    lines.extend(f"    public static string {key} => Get(nameof({key}));" for key in keys)
    lines.extend([
        "",
        "    /// <summary>缺少资源时显示键名,便于发现遗漏。</summary>",
        "    private static string Get(string key) => Manager.GetString(key) ?? key;",
        "}",
        "",
    ])
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = render()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8-sig") != expected:
            print("Strings.g.cs 与资源不一致,请运行 python scripts/generate-strings.py", file=sys.stderr)
            return 1
        print("资源访问器与 Strings.resx 一致")
    else:
        OUTPUT.write_text(expected, encoding="utf-8", newline="\n")
        print(f"已生成 {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
